// Original fictional layouts. No real circuit data or sporting reference times.
// Trigonometry is confined to this authoring step, never the timing path.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const names = [
 ['pocket-park','Pocket Park','Toybox county','A wide, forgiving first lap'],
 ['copper-cove','Copper Cove','The coast','Sweepers above the sea'],
 ['firefly-quay','Firefly Quay','Lantern islands','A warm night by the harbour'],
 ['juniper-run','Juniper Run','Green country','Link the forest bends'],
 ['saffron-sands','Saffron Sands','Sun country','Hot asphalt rewards a steady hand'],
 ['cloudbreak','Cloudbreak','Sky country','Long arcs on the high plateau'],
 ['marble-gardens','Marble Gardens','The old quarter','A compact technical loop'],
 ['bluebell-basin','Bluebell Basin','Lake country','Cool air and flowing corners'],
 ['lantern-loop','Lantern Loop','Lantern islands','Find the rhythm after dark'],
 ['foxglove','Foxglove','Green country','A winding ribbon through the hills'],
 ['cinder-works','Cinder Works','The foundry','Braking zones and quick exits'],
 ['saltwind','Saltwind','The coast','Carry speed through open curves'],
 ['tangerine-vale','Tangerine Vale','Sun country','Keep the tyres in their window'],
 ['paper-moon','Paper Moon','Lantern islands','A pale ribbon under midnight skies'],
 ['pinecrest','Pinecrest','Sky country','A cool, high-speed challenge'],
 ['rivet-yard','Rivet Yard','The foundry','Patient entries, strong exits'],
 ['pebble-beachway','Pebble Beachway','The coast','A long coastal sweep'],
 ['violet-hollow','Violet Hollow','Green country','Small bends with big consequences'],
 ['sunstone','Sunstone','Sun country','A hot lap through red stone'],
 ['kingfisher','Kingfisher','Lake country','A balanced all-rounder'],
 ['starlight-pier','Starlight Pier','Lantern islands','Bright corners on a dark shoreline'],
 ['thimble-ridge','Thimble Ridge','Sky country','The narrow mountain ribbon'],
 ['brassworks','Brassworks','The foundry','A final test of braking and grip'],
 ['cloverfield','Cloverfield','Green country','Join the corners into one motion'],
 ['aurora-bay','Aurora Bay','The far north','The longest lap of the toybox tour'],
];
const tracks = names.map(([id,name,region,character], index) => {
 const points=[];
 const size=index===0?160:240+(index%7)*32;
 const stretch=index===0?1.35:1.05+(index%4)*.16;
 for(let j=0;j<320;j++) {
  const a=j/320*2*Math.PI;
  const r=index===0?1+.08*Math.cos(3*a):1+.13*Math.sin((2+index%3)*a+index*.41)+.065*Math.cos((5+index%4)*a+index*.7);
  points.push([Math.round((size*stretch*r*Math.cos(a))*10)/10,Math.round((size*r*Math.sin(a))*10)/10]);
 }
 return {id,name,region,character,width:index===0?42:32+(index%3)*3,airTemp:14+(index*7)%22,trackTemp:22+(index*11)%35,grip:1,trim:1+index%5,night:index%4===2,points};
});
mkdirSync(resolve(root,'shared/generated'),{recursive:true});
const cpp=tracks.map(t=>`{"${t.id}","${t.name}","${t.region}","${t.character}",${t.width},${t.airTemp},${t.trackTemp},${t.grip},${t.trim},${t.night},{${t.points.map(p=>`{${p[0]},${p[1]}}`).join(',')}}}`).join(',\n');
writeFileSync(resolve(root,'shared/generated/circuits.inc'),`// Generated by native/scripts/generate-circuits.mjs.\n${cpp}\n`);
writeFileSync(resolve(root,'shared/generated/circuits.json'),JSON.stringify(tracks));
console.log(`Generated ${tracks.length} original fictional circuits.`);
