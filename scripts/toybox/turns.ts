// Turn numbers for the made-up circuits, from their own corner lists: each
// corner the layout counts as a turn (scripts/toybox/plan.ts: at least 12
// degrees, and the two halves of a split hairpin count once) has its apex in
// the middle of its arc, numbered in lap order from the start line. The Rookie
// Ring, the tutorial both editions share, keeps the web edition's turns (from
// its plan). Written to src/data/toybox/turns.ts. Run by `npm run toybox:tracks`; check one with
// `EDITION=toybox npx tsx scripts/turnmap.ts <slug> out.png --data`.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATALOG } from '../../src/data/toybox/catalog.js';
import { TURNS as WEB_TURNS } from '../../src/data/turns.js';
import { CIRCUITS } from './circuits.js';
import { layout } from './plan.js';

const OUT = join(import.meta.dirname, '..', '..', 'src', 'data', 'toybox', 'turns.ts');

/** Lap distance (metres along the layout) of each counted turn's apex, as layout() walks it. */
function turnApexes(corners: [number, number, number][], scale: number): number[] {
  const n = corners.length;
  const c = corners.map(([x, y, r]) => [x * scale, y * scale, r * scale]);
  const turn: number[] = [];
  const tan: number[] = [];
  for (let i = 0; i < n; i++) {
    const p = c[(i - 1 + n) % n], q = c[i], s = c[(i + 1) % n];
    let d = Math.atan2(s[1] - q[1], s[0] - q[0]) - Math.atan2(q[1] - p[1], q[0] - p[0]);
    while (d > Math.PI) d -= 2 * Math.PI;
    while (d < -Math.PI) d += 2 * Math.PI;
    turn.push(d);
    tan.push(q[2] * Math.tan(Math.abs(d) / 2));
  }
  const straight = (i: number) => Math.hypot(c[(i + 1) % n][0] - c[i][0], c[(i + 1) % n][1] - c[i][1]) - tan[i] - tan[(i + 1) % n];
  const arc = (i: number) => Math.abs(turn[i]) * c[i][2];
  const deg = (i: number) => (Math.abs(turn[i]) * 180) / Math.PI;
  // The lap starts halfway along the straight from corner 0 to corner 1.
  const mid: number[] = new Array(n);
  let s = straight(0) / 2;
  for (let k = 1; k <= n; k++) {
    const i = k % n;
    mid[i] = s + arc(i) / 2;
    s += arc(i) + straight(i);
  }
  const out: number[] = [];
  for (let k = 1; k <= n; k++) {
    const i = k % n;
    if (deg(i) < 12) continue;
    const prev = (i - 1 + n) % n;
    // The second half of a split hairpin: the turn's apex is between the two arcs.
    if (straight(prev) < 60 && Math.sign(turn[prev]) === Math.sign(turn[i]) && deg(prev) >= 12 && out.length) {
      out[out.length - 1] = (out[out.length - 1] + mid[i]) / 2;
      continue;
    }
    out.push(mid[i]);
  }
  return out;
}

const turns: Record<string, number[]> = {};
// The shared tutorial circuit: only its own entry, so no real circuit's slug reaches this edition.
for (const m of CATALOG.filter((c) => c.tutorial)) turns[m.slug] = WEB_TURNS[m.slug];
for (const c of CIRCUITS) {
  const meta = CATALOG.find((m) => m.slug === c.slug);
  if (!meta) continue;
  const lay = layout(c.corners, c.scale ?? 1);
  // The build smooths and resamples the layout, so scale to the built lap.
  const k = meta.length / lay.length;
  turns[c.slug] = turnApexes(c.corners, c.scale ?? 1).map((m) => Math.round(m * k));
  if (turns[c.slug].length !== meta.turns) console.warn(`${c.slug}: ${turns[c.slug].length} turns from the corner list, the catalog says ${meta.turns}`);
}
writeFileSync(
  OUT,
  `// Generated by scripts/toybox/turns.ts from the corner lists. Do not edit by hand.\n// Where each turn's apex is, in metres along the lap from the start line.\n\nexport const TURNS: Record<string, number[]> = ${JSON.stringify(turns)};\n`,
);
console.log(`wrote turns for ${Object.keys(turns).length} circuits`);
